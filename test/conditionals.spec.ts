import { expect, test } from 'vitest';
import { format } from '../lib/index.js';

test('conditional parts', () => {
  expect(format('[>=100]"A"0;[<=-100]"B"0;"C"0', 6.3)).toBe('C6');
  expect(format('[>=100]"A"0;[<=-100]"B"0;"C"0', -6.3)).toBe('-C6');
  expect(format('[>=100]"A"0;[<=0]"B"0;"C"0', 6.3)).toBe('C6');
  expect(format('[>=100]"A"0;[<=0]"B"0;"C"0', -6.3)).toBe('-B6');
  expect(format('[>=0]"A"0;[<=-100]"B"0;"C"0', 6.3)).toBe('A6');
  expect(format('[>=0]"A"0;[<=-100]"B"0;"C"0', -6.3)).toBe('-C6');
  expect(format('[>=0]"A"0;[<=0]"B"0;"C"0', 6.3)).toBe('A6');
  expect(format('[>=0]"A"0;[<=0]"B"0;"C"0', -6.3)).toBe('-B6');
  expect(format('[>=0]"A"0;[<=-100]"B"0', 6.3)).toBe('A6');
  expect(format('[>=100]"A"0;[<=0]"B"0', -6.3)).toBe('-B6');
  expect(format('[<=-100]"B"0;"C"0', 6.3)).toBe('C6');
  expect(format('[<=-100]"B"0;"C"0', -6.3)).toBe('C6');
  expect(format('[<=0]"B"0', 6.3)).toBe('6.3');
  expect(format('[<=0]"B"0', -6.3)).toBe('-B6');
  expect(format('[=6.3]"B"0', 6.3)).toBe('B6');
  expect(format('[=6.3]"B"0', -6.3)).toBe('-6.3');
  expect(format('[<>6]"B"0', 6.3)).toBe('B6');
  expect(format('[<>6]"B"0', -6.3)).toBe('-B6');
  expect(format('[=6.3]"B"0', 6.3)).toBe('B6');
  expect(format('[=6.3]"B"0', -6.3)).toBe('-6.3');
  expect(format('[>6]"A"0;[<-6]"B"0', 6.3)).toBe('A6');
  expect(format('[>6]"A"0;[<-6]"B"0', -6.3)).toBe('B6');
  expect(format('[>=100]"A"0;[<=-100]"B"0;"C"0;"D"@', 6.3)).toBe('C6');
  expect(format('[>=100]"A"0;[<=-100]"B"0;"C"0;"D"@', -6.3)).toBe('-C6');
  expect(format('[>=100]"A"-0;[<=-100]"B"-0;"C"-0', 6.3)).toBe('C-6');
  expect(format('[>=100]"A"-0;[<=-100]"B"-0;"C"-0', -6.3)).toBe('-C-6');
  expect(format('[>=100]"A"-#,##0;[<=0]"B"-#,##0;"C"-#,##0', 6.3)).toBe('C-6');
  expect(format('[>=100]"A"-#,##0;[<=0]"B"-#,##0;"C"-#,##0', -6.3)).toBe('-B-6');
  expect(format('[>=0]"A"-0;[<=-100]"B"-0;"C"-0', 6.3)).toBe('A-6');
  expect(format('[>=0]"A"-0;[<=-100]"B"-0;"C"-0', -6.3)).toBe('-C-6');
  expect(format('[>=0]"A"-0;[<=0]"B"-0;"C"-0', 6.3)).toBe('A-6');
  expect(format('[>=0]"A"-0;[<=0]"B"-0;"C"-0', -6.3)).toBe('-B-6');

  expect(format('[>=100]"A"0;[<=-100]"B"0', 6.3)).toBe('######');
  expect(format('[>=100]"A"0;[<=-100]"B"0', -6.3)).toBe('######');
  expect(format('[>=0]"A"0;[<=-100]"B"0', -6.3)).toBe('######');
  expect(format('[>=100]"A"0;[<=0]"B"0', 6.3)).toBe('######');
  expect(() => format('[>=100]"A"0;[<=-100]"B"0;"C"0;"D"0', '')).toThrow();
  expect(() => format('[>=100]"A"0;[<=-100]"B"0;"C"0;"D"0', '')).toThrow();
  expect(() => format('[<-25]0;[>25]0;0;"foo".#', '')).toThrow();
});

