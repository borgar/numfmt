  expect(format('ss', date)).toBe('06');
  expect(format('sss', date)).toBe('06');
  expect(format('ssss', date)).toBe('06');
  expect(format('sssss', date)).toBe('06');
  expect(format('ssssss', date)).toBe('06');
  expect(format('S', date)).toBe('6');
  expect(format('SS', date)).toBe('06');
  expect(format('SSS', date)).toBe('06');
  expect(format('SSSS', date)).toBe('06');
  expect(format('SSSSS', date)).toBe('06');
  expect(format('SSSSSS', date)).toBe('06');
  expect(format('m', date)).toBe('1');
  expect(format('mm', date)).toBe('01');
  expect(format('mmm', date)).toBe('Jan');
  expect(format('mmmm', date)).toBe('January');
  expect(format('mmmmm', date)).toBe('J');
  expect(format('mmmmmm', date)).toBe('January');
  expect(format('M', date)).toBe('1');
  expect(format('MM', date)).toBe('01');
  expect(format('MMM', date)).toBe('Jan');
  expect(format('MMMM', date)).toBe('January');
  expect(format('MMMMM', date)).toBe('J');
  expect(format('MMMMMM', date)).toBe('January');
  expect(format('h', date)).toBe('3');
  expect(format('hh', date)).toBe('03');
  expect(format('hhh', date)).toBe('03');
  expect(format('hhhh', date)).toBe('03');
  expect(format('hhhhh', date)).toBe('03');
  expect(format('hhhhhh', date)).toBe('03');
  expect(format('H', date)).toBe('3');
  expect(format('HH', date)).toBe('03');
  expect(format('HHH', date)).toBe('03');
  expect(format('HHHH', date)).toBe('03');
  expect(format('HHHHH', date)).toBe('03');
  expect(format('HHHHHH', date)).toBe('03');
  expect(format('a', date)).toBe('a');
  expect(format('aa', date)).toBe('aa');
  expect(format('aaa', date)).toBe('Sat');
  expect(format('aaaa', date)).toBe('Saturday');
  expect(format('aaaaa', date)).toBe('Saturday');
  expect(format('aaaaaa', date)).toBe('Saturday');
  expect(format('d', date)).toBe('2');
  expect(format('dd', date)).toBe('02');
  expect(format('ddd', date)).toBe('Sat');
  expect(format('dddd', date)).toBe('Saturday');
  expect(format('ddddd', date)).toBe('Saturday');
  expect(format('dddddd', date)).toBe('Saturday');
  expect(format('D', date)).toBe('2');
  expect(format('DD', date)).toBe('02');
  expect(format('DDD', date)).toBe('Sat');
  expect(format('DDDD', date)).toBe('Saturday');
  expect(format('DDDDD', date)).toBe('Saturday');
  expect(format('DDDDDD', date)).toBe('Saturday');
  expect(format('y', date)).toBe('09');
  expect(format('yy', date)).toBe('09');
  expect(format('yyy', date)).toBe('1909');
  expect(format('yyyy', date)).toBe('1909');
  expect(format('yyyyy', date)).toBe('1909');
  expect(format('yyyyyy', date)).toBe('1909');
  expect(format('Y', date)).toBe('09');
  expect(format('YY', date)).toBe('09');
  expect(format('YYY', date)).toBe('1909');
  expect(format('YYYY', date)).toBe('1909');
  expect(format('YYYYY', date)).toBe('1909');
