test('Date specifiers: month vs. minute', () => {
  expect(format('h', date)).toBe('3');
  expect(format('m', date)).toBe('1');
  expect(format('s', date)).toBe('6');

  expect(format('h-h', date)).toBe('3-3');
  expect(format('h-m', date)).toBe('3-4');
  expect(format('h-s', date)).toBe('3-6');
  expect(format('m-h', date)).toBe('1-3');
  expect(format('m-m', date)).toBe('1-1');
  expect(format('m-s', date)).toBe('4-6');
  expect(format('s-h', date)).toBe('6-3');
  expect(format('s-m', date)).toBe('6-4');
  expect(format('s-s', date)).toBe('6-6');

  expect(format('h-h-m', date)).toBe('3-3-4');
  expect(format('h-h-s', date)).toBe('3-3-6');
  expect(format('h-m-h', date)).toBe('3-4-3');
  expect(format('h-m-m', date)).toBe('3-4-1');
  expect(format('h-m-s', date)).toBe('3-4-6');
  expect(format('h-s-h', date)).toBe('3-6-3');
  expect(format('h-s-m', date)).toBe('3-6-4');
  expect(format('h-s-s', date)).toBe('3-6-6');
  expect(format('m-h-h', date)).toBe('1-3-3');
  expect(format('m-h-m', date)).toBe('1-3-4');
  expect(format('m-h-s', date)).toBe('1-3-6');
  expect(format('m-m-h', date)).toBe('1-1-3');
  expect(format('m-m-m', date)).toBe('1-1-1');
  expect(format('m-m-s', date)).toBe('1-4-6');
  expect(format('m-s-h', date)).toBe('4-6-3');
  expect(format('m-s-m', date)).toBe('4-6-1');
  expect(format('m-s-s', date)).toBe('4-6-6');
  expect(format('s-h-h', date)).toBe('6-3-3');
  expect(format('s-h-m', date)).toBe('6-3-4');
  expect(format('s-h-s', date)).toBe('6-3-6');
  expect(format('s-m-h', date)).toBe('6-4-3');
  expect(format('s-m-m', date)).toBe('6-4-1');
  expect(format('s-m-s', date)).toBe('6-4-6');
  expect(format('s-s-h', date)).toBe('6-6-3');
  expect(format('s-s-m', date)).toBe('6-6-4');

  expect(format('h-m-m-s', date)).toBe('3-4-4-6');
  expect(format('h-m-s-m', date)).toBe('3-4-6-1');
  expect(format('h-s-m-m', date)).toBe('3-6-4-1');
  expect(format('m-h-m-s', date)).toBe('1-3-4-6');
  expect(format('m-h-s-m', date)).toBe('1-3-6-4');
  expect(format('m-m-h-s', date)).toBe('1-1-3-6');
  expect(format('m-m-s-h', date)).toBe('1-4-6-3');
  expect(format('m-s-h-m', date)).toBe('4-6-3-4');
  expect(format('m-s-m-h', date)).toBe('4-6-1-3');
  expect(format('s-h-m-m', date)).toBe('6-3-4-1');
  expect(format('s-m-h-m', date)).toBe('6-4-3-4');
  expect(format('s-m-m-h', date)).toBe('6-4-1-3');

  expect(format('y-m-d', date)).toBe('09-1-2');
  expect(format('d-m-y', date)).toBe('2-1-09');
  expect(format('yy-mm-dd', date)).toBe('09-01-02');

  expect(format('yyyy', date)).toBe('1909');
  expect(format('yyyy-mm', date)).toBe('1909-01');
  expect(format('yyyy-mm-dd', date)).toBe('1909-01-02');
  expect(format('yyyy-mm-dd\\Thh', date)).toBe('1909-01-02T03');
  expect(format('yyyy-mm-dd\\Thh-mm', date)).toBe('1909-01-02T03-04');
  expect(format('yyyy-mm-dd\\Thh-mm-ss', date)).toBe('1909-01-02T03-04-06');
  expect(format('yyyy-mm-dd\\Thh-mm-ss.000', date)).toBe('1909-01-02T03-04-05.678');

  expect(format('yyyy-mm-dd\\Thh-mm-ss.000', 60)).toBe('1900-02-29T00-00-00.000');
  expect(format('yyyy-mm-dd\\Thh-mm-ss.000', 61)).toBe('1900-03-01T00-00-00.000');
});

