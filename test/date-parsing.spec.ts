  expect(format('[sss]', date)).toBe('284267046');
  expect(format('[ssss]', date)).toBe('284267046');
  // fractional seconds
  expect(format('[s].0', date)).toBe('284267045.7');
  expect(format('[s].00', date)).toBe('284267045.68');
